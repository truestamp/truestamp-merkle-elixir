// Upstream assertions on these files (github.com/cosmos/ics23/go@v0.11.0):
// go/vectors_test.go:9-39 TestVectors verifies every single file
// (go/vectors_data_test.go:43-48); go/vectors_test.go:41-75 TestBatchVectors
