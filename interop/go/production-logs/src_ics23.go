// The Tendermint vectors of github.com/cosmos/ics23 (Apache-2.0), vendored from
// the repository's testdata/tendermint at tag go/v0.11.0 (commit
// 16ead2358595639df8ee8c31306ac0eeda2e904f; the directory sits outside the Go
// module github.com/cosmos/ics23/go@v0.11.0, whose go/ tree is identical to the
// tag's). They were generated by github.com/confio/proofs-tendermint (testgen,
// Makefile:14-24) from tendermint v0.33.2 crypto/merkle SimpleProofsFromMap,
// whose tree has the RFC 9162 shape over sorted keys. A leaf is
// SHA-256(0x00 || varint(len key) || key || varint(32) || SHA-256(value)); an
// inner op is SHA-256(0x01 || left || right) with the sibling in the op's prefix
// (left sibling) or suffix (right sibling). ics23 carries no leaf index and no
// tree size.

